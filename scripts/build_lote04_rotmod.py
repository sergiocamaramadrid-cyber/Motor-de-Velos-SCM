def write_file(name, rows):
    path = OUT_DIR / f"{name}_rotmod.dat"
    with open(path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(" ".join(f"{x:.6g}" for x in r) + "\n")


def main():
    for galaxy, rows in DATA.items():
        write_file(galaxy, rows)
    print(f"✔ LOTE04 escrito ({len(DATA)} galaxias)")


if __name__ == "__main__":
    main()
