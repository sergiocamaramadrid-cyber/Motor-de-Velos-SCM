def write_file(name: str, rows: list[list[float]]) -> None:
    path = OUT_DIR / f"{name}_rotmod.dat"
    with open(path, "w", encoding="utf-8") as f:
        for row in rows:
            f.write(" ".join(f"{x:.6g}" for x in row) + "\n")


def main() -> None:
    for galaxy, rows in DATA.items():
        write_file(galaxy, rows)
    print(f"✔ Written {len(DATA)} galaxies to {OUT_DIR}")


if __name__ == "__main__":
    main()
