#!/usr/bin/env python3
"""
run_h3_experiment.py – Test de H3: Difusión radial de ΔF₃.

Correlates per-galaxy autocorrelation metrics of the radial ΔF₃ profile
against a global environmental proxy (delta_mass) using Spearman rank
correlation and a robust HC3 bootstrap estimator of the OLS slope β.

Multiple minimum-point thresholds (e.g. 8, 10, 12) are tested to demonstrate
that any signal is not an artefact of an arbitrary cut.

Inputs
------
f3_profiles  : CSV with columns [galaxy, r (or synonym), delta_F3].
               Generated by scripts/generate_sparc_radial_profiles.py.
env_data     : CSV with columns [galaxy, delta_mass, delta_mode].
               Generated by scripts/generate_sparc_delta_env.py.

Outputs (inside --out directory)
---------------------------------
final_report.csv         — summary metrics for every threshold × metric.
all_rejected.csv         — galaxies excluded from any threshold (QC log).
min_points_<N>/
    data_merged.csv      — merged radial + env data used for this threshold.
    rejected_galaxies.csv— galaxies rejected at this specific threshold.
    scatter_<metric>.png — scatter plots with HC3 regression line.

Usage
-----
::

    python run_h3_experiment.py \\
        data/sparc_full_radial.csv \\
        data/SPARC/SPARC_with_delta_real.csv \\
        --out ./H3_results --thresholds 8,10,12 --n_boot 3000

"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import spearmanr
import statsmodels.api as sm


# ---------------------------------------------------------------------------
# Bootstrap β estimator
# ---------------------------------------------------------------------------

def bootstrap_beta(df, x_col, y_col, n_boot=2000, seed=42):
    """Bootstrap-robust, reproducible slope estimate with HC3 covariance.

    Parameters
    ----------
    df : pd.DataFrame
        Input data (must contain *x_col* and *y_col*).
    x_col, y_col : str
        Column names for the predictor and response.
    n_boot : int
        Number of bootstrap iterations.
    seed : int
        RNG seed (guarantees reproducibility).

    Returns
    -------
    dict with keys: betas, mean, ci_low, ci_high, valid_iters.
    """
    rng = np.random.default_rng(seed)

    data = df[[x_col, y_col]].copy()
    data[x_col] = pd.to_numeric(data[x_col], errors='coerce')
    data[y_col] = pd.to_numeric(data[y_col], errors='coerce')
    data = data.dropna().reset_index(drop=True)

    if len(data) < 8:
        return {
            'betas': np.array([]),
            'mean': np.nan,
            'ci_low': np.nan,
            'ci_high': np.nan,
            'valid_iters': 0,
        }

    betas = []
    for _ in range(n_boot):
        idx = rng.choice(len(data), size=len(data), replace=True)
        sample = data.iloc[idx]

        X = sm.add_constant(sample[[x_col]], has_constant='add')
        y = sample[y_col]

        try:
            model = sm.OLS(y, X).fit(cov_type='HC3')
            beta_val = model.params.get(x_col, np.nan)
            betas.append(beta_val)
        except Exception:
            betas.append(np.nan)

    betas = np.asarray(betas, dtype=float)
    valid = betas[np.isfinite(betas)]

    if len(valid) == 0:
        return {
            'betas': betas,
            'mean': np.nan,
            'ci_low': np.nan,
            'ci_high': np.nan,
            'valid_iters': 0,
        }

    return {
        'betas': betas,
        'mean': float(np.mean(valid)),
        'ci_low': float(np.percentile(valid, 2.5)),
        'ci_high': float(np.percentile(valid, 97.5)),
        'valid_iters': int(len(valid)),
    }


# ---------------------------------------------------------------------------
# Main experiment
# ---------------------------------------------------------------------------

def run_h3_experiment(
    f3_path,
    delta_path,
    base_out_dir,
    thresholds=(8, 10, 12),
    n_boot=2000,
    seed=42,
    min_galaxies=15,
):
    """Run the full H3 experiment over multiple min-point thresholds.

    Parameters
    ----------
    f3_path : str or Path
        CSV file with per-radial-point ΔF₃ profiles.
    delta_path : str or Path
        CSV file with per-galaxy environmental deltas.
    base_out_dir : str or Path
        Root output directory; sub-directories per threshold are created here.
    thresholds : iterable of int
        Minimum-radial-point thresholds to evaluate.
    n_boot : int
        Bootstrap iterations for β estimation.
    seed : int
        Global RNG seed.
    min_galaxies : int
        Minimum number of galaxies required to report a metric result.

    Returns
    -------
    pd.DataFrame
        Summary table with one row per (threshold, metric) combination.
    """
    f3_df = pd.read_csv(f3_path)
    delta_df = pd.read_csv(delta_path)

    # ------------------------------------------------------------------ #
    # Filter delta to 'mass' mode if delta_mode column is present          #
    # ------------------------------------------------------------------ #
    if 'delta_mode' in delta_df.columns:
        delta_mass = delta_df[delta_df['delta_mode'] == 'mass'].copy()
    else:
        delta_mass = delta_df.copy()
    delta_mass = delta_mass[['galaxy', 'delta_mass']].dropna()

    # ------------------------------------------------------------------ #
    # Identify radius column                                               #
    # ------------------------------------------------------------------ #
    r_col = None
    for col in ['r', 'R_kpc', 'radius_kpc', 'R', 'r_kpc']:
        if col in f3_df.columns:
            r_col = col
            break
    if r_col is None:
        raise ValueError(
            f"No radius column found in {f3_path}. "
            "Expected one of: r, R_kpc, radius_kpc, R, r_kpc."
        )

    summary_report = []   # accumulated across all thresholds
    all_rejected = []

    for m_points in thresholds:
        print(f"\n>>> Umbral: {m_points} puntos mínimos")
        run_dir = Path(base_out_dir) / f"min_points_{m_points}"
        run_dir.mkdir(parents=True, exist_ok=True)

        results = []
        rejected = []

        for gal, group in f3_df.groupby('galaxy'):
            group = group.sort_values(r_col)

            if 'delta_F3' not in group.columns:
                rejected.append({'galaxy': gal, 'n_points': 0, 'reason': 'no_delta_F3'})
                continue

            clean_f3 = group['delta_F3'].dropna().values
            n_valid = len(clean_f3)

            if n_valid < m_points:
                rejected.append({'galaxy': gal, 'n_points': n_valid, 'reason': 'below_threshold'})
                continue

            rho_l1 = pd.Series(clean_f3).autocorr(lag=1) if n_valid >= 3 else np.nan
            rho_l2 = pd.Series(clean_f3).autocorr(lag=2) if n_valid >= 4 else np.nan
            roughness = float(np.std(np.diff(clean_f3))) if n_valid >= 2 else np.nan

            results.append({
                'galaxy': gal,
                'rho_lag1': rho_l1,
                'rho_lag2': rho_l2,
                'roughness': roughness,
                'n_points': n_valid,
            })

        res_df = pd.DataFrame(results) if results else pd.DataFrame(
            columns=['galaxy', 'rho_lag1', 'rho_lag2', 'roughness', 'n_points']
        )
        merged = pd.merge(res_df, delta_mass, on='galaxy', how='inner')
        merged.to_csv(run_dir / 'data_merged.csv', index=False)
        pd.DataFrame(rejected).to_csv(run_dir / 'rejected_galaxies.csv', index=False)
        all_rejected.extend(rejected)

        print(f"  Galaxias válidas: {len(merged)}")

        for metric in ['rho_lag1', 'rho_lag2', 'roughness']:
            sub = merged.dropna(subset=['delta_mass', metric]).copy()
            nsub = len(sub)
            print(f"    Métrica {metric}: {nsub} galaxias")

            if nsub < min_galaxies:
                print(f"      -> < {min_galaxies}, omitido.")
                continue

            if nsub >= 2:
                rho_s, p_s = spearmanr(sub['delta_mass'], sub[metric])
            else:
                rho_s, p_s = np.nan, np.nan

            boot = bootstrap_beta(sub, 'delta_mass', metric, n_boot=n_boot, seed=seed)

            summary_report.append({
                'threshold': m_points,
                'metric': metric,
                'spearman_rho': rho_s,
                'spearman_p': p_s,
                'boot_mean': boot['mean'],
                'boot_ci_low': boot['ci_low'],
                'boot_ci_high': boot['ci_high'],
                'boot_valid_iters': boot['valid_iters'],
                'n_galaxies': nsub,
            })

            if nsub >= 5:
                fig, ax = plt.subplots(figsize=(6, 5))
                ax.scatter(sub['delta_mass'], sub[metric], alpha=0.6, edgecolors='k')
                X = sm.add_constant(sub[['delta_mass']])
                model = sm.OLS(sub[metric], X).fit(cov_type='HC3')
                x_plot = np.linspace(sub['delta_mass'].min(), sub['delta_mass'].max(), 100)
                y_plot = model.params.iloc[0] + model.params.iloc[1] * x_plot
                ax.plot(x_plot, y_plot, 'r-', label=f'β = {model.params.iloc[1]:.3f}')
                ax.set_xlabel(r'$\delta_{\rm mass}$')
                ax.set_ylabel(metric)
                ax.set_title(f'Umbral {m_points} puntos')
                ax.legend()
                ax.grid(alpha=0.3)
                fig.tight_layout()
                fig.savefig(run_dir / f'scatter_{metric}.png', dpi=150)
                plt.close(fig)

    summary_df = pd.DataFrame(summary_report)
    summary_df.to_csv(Path(base_out_dir) / 'final_report.csv', index=False)
    pd.DataFrame(all_rejected).to_csv(Path(base_out_dir) / 'all_rejected.csv', index=False)

    print("\n=== RESUMEN FINAL ===")
    if not summary_df.empty:
        print(summary_df.to_string(index=False))
    else:
        print("  (sin resultados — ningún umbral alcanzó el mínimo de galaxias)")
    print(f"\nTotal galaxias rechazadas (acumulado): {len(all_rejected)}")
    print(f"Reportes guardados en {Path(base_out_dir)}")

    return summary_df


# ---------------------------------------------------------------------------
# CLI entry-point
# ---------------------------------------------------------------------------

if __name__ == '__main__':
    parser = argparse.ArgumentParser(
        description='Ejecuta el experimento H3 (difusión radial de ΔF₃) '
                    'con múltiples umbrales de puntos mínimos.',
    )
    parser.add_argument(
        'f3_profiles',
        help='CSV de perfiles ΔF₃ por radio (sparc_full_radial.csv)',
    )
    parser.add_argument(
        'env_data',
        help='CSV de datos ambientales por galaxia (SPARC_with_delta_real.csv)',
    )
    parser.add_argument('--out', default='./H3_results', help='Directorio de salida')
    parser.add_argument(
        '--thresholds',
        default='8,10,12',
        help='Umbrales de puntos mínimos separados por coma (default: 8,10,12)',
    )
    parser.add_argument('--n_boot', type=int, default=2000, help='Iteraciones bootstrap')
    parser.add_argument('--seed', type=int, default=42, help='Semilla aleatoria')
    parser.add_argument(
        '--min_galaxies',
        type=int,
        default=15,
        help='Mínimo de galaxias para reportar una métrica',
    )
    args = parser.parse_args()

    thresholds = [int(x) for x in args.thresholds.split(',') if x.strip().isdigit()]
    if not thresholds:
        parser.error('--thresholds debe contener al menos un entero positivo.')

    run_h3_experiment(
        args.f3_profiles,
        args.env_data,
        args.out,
        thresholds=thresholds,
        n_boot=args.n_boot,
        seed=args.seed,
        min_galaxies=args.min_galaxies,
    )
